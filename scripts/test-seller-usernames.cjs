const { PGlite } = require('@electric-sql/pglite');
const assert = require('node:assert/strict');
const fs = require('fs');
(async () => {
  const db = new PGlite();
  await db.exec(
    `create role anon; create role authenticated; create role service_role; create schema auth; create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub', true),'')::uuid$$; grant usage on schema auth to authenticated,anon; grant execute on function auth.uid() to authenticated,anon; create table public.users(id bigint generated by default as identity primary key,created_at timestamptz default now(),name text,phone text,user_id uuid); insert into public.users(id,name,user_id) values(42,'María López','00000000-0000-0000-0000-000000000042'),(43,'María','00000000-0000-0000-0000-000000000043'),(44,'🎉',null),(45,'Ána','00000000-0000-0000-0000-000000000045');`
  );
  const migration = fs.readFileSync(
    process.cwd() + '/docs/sql/seller-usernames.sql',
    'utf8'
  );
  await db.exec(migration);
  const rows = (await db.query('select id,username from users order by id'))
    .rows;
  assert.deepEqual(
    rows.map((r) => r.username),
    ['maria-42', 'maria-43', 'vendedor-44', 'ana-45']
  );
  await db.exec(migration);
  assert.equal(
    (await db.query('select count(*)::int n from seller_usernames')).rows[0].n,
    4
  );
  await db.exec(
    "update users set username='MARIA-VINTAGE',instagram_username='Maria.Vintage' where id=42"
  );
  assert.equal(
    (await db.query('select username from users where id=42')).rows[0].username,
    'maria-vintage'
  );
  assert.equal(
    (
      await db.query(
        "select owner_id from seller_usernames where username='maria-42'"
      )
    ).rows[0].owner_id,
    42
  );
  async function fails(sql, code) {
    try {
      await db.exec(sql);
      assert.fail('Expected rejection: ' + sql);
    } catch (e) {
      assert.equal(e.code, code, e.message);
    }
  }
  await fails(
    "update users set username='maria-42',phone='changed' where id=43",
    '23505'
  );
  assert.equal(
    (await db.query('select phone from users where id=43')).rows[0].phone,
    null
  );
  await fails("update users set username='admin' where id=43", '23514');
  await fails("update users set username='maria.vintage' where id=43", '23514');
  await fails(
    "update users set instagram_username='https://evil.example' where id=43",
    '23514'
  );
  await fails(
    "insert into users(id,name,user_id) values(47,'Duplicated login','00000000-0000-0000-0000-000000000042')",
    '23505'
  );
  await db.exec("update users set username='maria-42' where id=42");
  await db.exec("insert into users(id,name) values(46,'María')");
  assert.equal(
    (await db.query('select username from users where id=46')).rows[0].username,
    'maria-46'
  );
  await db.exec('delete from users where id=46');
  await fails("update users set username='maria-46' where id=43", '23505');
  await db.exec(
    `grant select,insert,update on users to authenticated,anon; grant usage on sequence users_id_seq to authenticated,anon; set role authenticated; set request.jwt.claim.sub='00000000-0000-0000-0000-000000000042';`
  );
  await db.exec("update users set username='maria-second' where id=42");
  await fails("update users set username='stolen-name' where id=43", '42501');
  await fails(
    "update users set user_id='00000000-0000-0000-0000-000000000042', username='stolen-name' where id=43",
    '42501'
  );
  await fails(
    "insert into seller_usernames values('stolen-name',42,now())",
    '42501'
  );
  await fails('select * from seller_usernames', '42501');
  await db.exec("reset role; set role anon; set request.jwt.claim.sub='';");
  await fails("update users set username='anonymous' where id=42", '42501');
  await db.exec('reset role');
  console.log(
    'PASS: migration, idempotence, accented/duplicate/empty names, automatic creation, alias history, unique reservations, atomic rollback, validation, deleted reservations, ownership and table permissions.'
  );
  await db.close();
})().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
